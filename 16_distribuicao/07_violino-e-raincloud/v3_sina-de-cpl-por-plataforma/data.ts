/**
 * Custo por lead de cada campanha do semestre, em reais, por plataforma de mídia, com a marcação de
 * quais usam criativo em vídeo. Dado fictício e fixo, sem correspondência com a base real e sem nome
 * de plataforma de verdade: os valores saíram uma vez de um gerador com semente e estão escritos
 * abaixo.
 *
 * Uma linha por campanha, com código. O código é a semente da posição lateral do ponto dentro da
 * forma, que não carrega informação nenhuma e por isso precisa ser a mesma em todo render.
 *
 * As quatro plataformas têm tamanhos bem diferentes, de 120 a 420 campanhas, porque a largura da
 * forma aqui é por contagem: a plataforma maior desenha a forma mais larga.
 */

export interface Campaign {
  /** Código fictício da campanha. */
  readonly id: string;
  /** Custo por lead, em reais. */
  readonly cpl: number;
  /** A campanha usa criativo em vídeo. */
  readonly video: boolean;
}

export interface Platform {
  readonly id: string;
  readonly name: string;
  readonly campaigns: readonly Campaign[];
}

/**
 * Campanhas que rodaram no semestre sem gerar nenhum lead. CPL não existe com denominador zero:
 * ficam fora da forma e contadas no rodapé, nunca como zero.
 */
export const WITHOUT_LEADS = 46;

/** Primeiro a lista das campanhas em vídeo, depois a das demais; o código sai do prefixo e da posição. */
function platform(id: string, name: string, prefix: number, video: readonly number[], other: readonly number[]): Platform {
  return {
    id,
    name,
    campaigns: [
      ...video.map((cpl, index) => ({ id: `CP ${String(prefix + index)}`, cpl, video: true })),
      ...other.map((cpl, index) => ({ id: `CP ${String(prefix + video.length + index)}`, cpl, video: false })),
    ],
  };
}

